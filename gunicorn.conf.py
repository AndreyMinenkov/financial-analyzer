# gunicorn.conf.py
import os

# ============================================================
# ПРИВЯЗКА И ПОРТ
# ============================================================
bind = '0.0.0.0:5000'

# ============================================================
# WORKERS
# ============================================================
workers = int(os.environ.get('GUNICORN_WORKERS', 2))
worker_class = 'sync'
threads = 1
worker_connections = 100

# ============================================================
# ТАЙМАУТЫ
# ============================================================
timeout = 600          # 10 минут на обработку большого Excel
graceful_timeout = 30  # 30 секунд на завершение текущих запросов
keepalive = 5

# ============================================================
# ПЕРЕЗАПУСК WORKERS (защита от утечек памяти)
# ============================================================
max_requests = 1000
max_requests_jitter = 100

# ============================================================
# ЛОГГИРОВАНИЕ
# ============================================================
LOG_DIR = '/var/log/financial-analyzer'
os.makedirs(LOG_DIR, exist_ok=True)

# Access-лог (все HTTP-запросы)
accesslog = os.path.join(LOG_DIR, 'access.log')
access_log_format = '%(h)s %(l)s %(u)s %(t)s "%(r)s" %(s)s %(b)s "%(f)s" "%(a)s" %(D)sμs'

# Error-лог (ошибки gunicorn)
errorlog = os.path.join(LOG_DIR, 'gunicorn-error.log')

# Уровень логгирования
loglevel = 'info'

# ============================================================
# PID-ФАЙЛ (для systemd)
# ============================================================
pidfile = '/var/run/financial-analyzer.pid'

# ============================================================
# ЗАПУСК ОТ НЕПРИВИЛЕГИРОВАННОГО ПОЛЬЗОВАТЕЛЯ
# ============================================================
# Раскомментировать после создания пользователя:
# user = 'financial-analyzer'
# group = 'financial-analyzer'

# ============================================================
# НАСТРОЙКИ БЕЗОПАСНОСТИ
# ============================================================
umask = 0o022
daemon = False  # systemd управляет демонизацией